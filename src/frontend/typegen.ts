// OpenAPI -> TypeScript types (component schemas + an Endpoints map), used by `farsi-mock frontend`.
type Obj = Record<string, any>;
const isObj = (v: unknown): v is Obj => !!v && typeof v === "object" && !Array.isArray(v);
const METHODS = ["get", "post", "put", "patch", "delete"];

export function tsIdent(name: string): string {
  const s = name.replace(/[^A-Za-z0-9_$]+(.)?/g, (_m, c: string | undefined) => (c ? c.toUpperCase() : "")).replace(/^[^A-Za-z_$]+/, "");
  return s ? s[0].toUpperCase() + s.slice(1) : "Schema";
}
const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

export function schemaToTs(node: unknown, depth = 0, indent = ""): string {
  if (!isObj(node) || depth > 12) return "unknown";
  const nullable = node.nullable === true || node["x-nullable"] === true || (Array.isArray(node.type) && node.type.includes("null"));
  const withNull = (t: string) => (nullable && !/\bnull$/.test(t) ? `${t} | null` : t);
  if (typeof node.$ref === "string") return withNull(tsIdent(node.$ref.split("/").pop()!));
  if (Array.isArray(node.allOf)) return withNull(node.allOf.map((x: unknown) => paren(schemaToTs(x, depth + 1, indent))).join(" & ") || "unknown");
  for (const k of ["oneOf", "anyOf"]) if (Array.isArray(node[k])) return withNull([...new Set(node[k].map((x: unknown) => schemaToTs(x, depth + 1, indent)))].join(" | ") || "unknown");
  if (Array.isArray(node.enum)) return withNull(node.enum.map((v: unknown) => JSON.stringify(v)).join(" | "));
  if (node.const !== undefined) return withNull(JSON.stringify(node.const));
  const type = Array.isArray(node.type) ? node.type.find((t: string) => t !== "null") : node.type ?? (node.properties ? "object" : node.items ? "array" : undefined);
  switch (type) {
    case "string": return withNull(node.format === "binary" ? "Blob | string" : "string");
    case "integer": case "number": return withNull("number");
    case "boolean": return withNull("boolean");
    case "null": return "null";
    case "array": return withNull(`${paren(schemaToTs(node.items, depth + 1, indent))}[]`);
    case "object": {
      const req = new Set<string>(Array.isArray(node.required) ? node.required : []);
      const inner = indent + "  ";
      const props = Object.entries((node.properties ?? {}) as Obj).map(([k, v]) => {
        const doc = isObj(v) && typeof v.description === "string" ? `${inner}/** ${v.description.replace(/\*\//g, "* /").replace(/\s+/g, " ")} */\n` : "";
        return `${doc}${inner}${key(k)}${req.has(k) ? "" : "?"}: ${schemaToTs(v, depth + 1, inner)};`;
      });
      const ap = node.additionalProperties;
      if (ap && props.length === 0) return withNull(`Record<string, ${ap === true ? "unknown" : schemaToTs(ap, depth + 1, indent)}>`);
      if (ap) props.push(`${inner}[key: string]: ${ap === true ? "unknown" : "unknown"};`);
      return withNull(props.length ? `{\n${props.join("\n")}\n${indent}}` : "Record<string, unknown>");
    }
    default: return "unknown";
  }
}
const paren = (t: string) => (/[|&]/.test(t) && !/^\{[\s\S]*\}$/.test(t) ? `(${t})` : t);

function bodySchema(r: Obj): Obj | undefined {
  if (!isObj(r)) return undefined;
  if (r.schema) return r.schema;
  const c = (r.content ?? {}) as Obj;
  const k = Object.keys(c).find((x) => /json/i.test(x)) ?? Object.keys(c)[0];
  return k ? c[k]?.schema : undefined;
}
function deref(doc: Obj, n: unknown): Obj {
  let x = n as Obj;
  for (let i = 0; i < 10 && isObj(x) && typeof x.$ref === "string" && !/\/schemas\/|\/definitions\//.test(x.$ref); i++) {
    x = x.$ref.slice(2).split("/").reduce((o: Obj | undefined, k: string) => o?.[k], doc) as Obj;
  }
  return x;
}

/** TypeScript source with one type per component schema and an `Endpoints` map ("GET /products/{id}" -> { response, body, query, params }). */
export function openApiToTs(doc: unknown, opts: { endpointsName?: string } = {}): string {
  if (!isObj(doc)) throw new Error("farsi-mock: OpenAPI document must be an object");
  const out: string[] = ["// Generated by farsi-mock from the OpenAPI spec. Do not edit; re-run `farsi-mock frontend`.", ""];
  const schemas = (doc.components?.schemas ?? doc.definitions ?? {}) as Obj;
  for (const [name, s] of Object.entries(schemas)) {
    const t = schemaToTs(s);
    if (isObj(s) && typeof s.description === "string") out.push(`/** ${s.description.replace(/\*\//g, "* /").replace(/\s+/g, " ")} */`);
    out.push(t.startsWith("{") ? `export interface ${tsIdent(name)} ${t}` : `export type ${tsIdent(name)} = ${t};`, "");
  }
  const eps: string[] = [];
  for (const [path, item] of Object.entries((doc.paths ?? {}) as Obj)) {
    if (!isObj(item)) continue;
    for (const m of METHODS) {
      const op = item[m];
      if (!isObj(op)) continue;
      const res = (op.responses ?? {}) as Obj;
      const code = Object.keys(res).find((c) => /^2\d\d$/.test(c)) ?? (res.default ? "default" : undefined);
      const rs = code ? bodySchema(deref(doc, res[code])) : undefined;
      const response = code === "204" || !rs ? "undefined" : schemaToTs(rs, 0, "    ");
      const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map((p: unknown) => deref(doc, p)).filter(isObj);
      const group = (where: string) => {
        const ps = params.filter((p) => p.in === where);
        if (!ps.length) return undefined;
        return `{ ${ps.map((p) => `${key(String(p.name))}${p.required ? "" : "?"}: ${schemaToTs(p.schema ?? p, 0, "    ")}`).join("; ")} }`;
      };
      const bodyParam = params.find((p) => p.in === "body");
      const rb = op.requestBody ? bodySchema(deref(doc, op.requestBody)) : bodyParam?.schema;
      const lines = [`    response: ${response};`];
      if (rb) lines.push(`    body: ${schemaToTs(rb, 0, "    ")};`);
      const q = group("query"), pp = group("path");
      if (q) lines.push(`    query: ${q};`);
      if (pp) lines.push(`    params: ${pp};`);
      const summary = typeof op.summary === "string" ? `  /** ${op.summary.replace(/\*\//g, "* /").replace(/\s+/g, " ")} */\n` : "";
      eps.push(`${summary}  ${JSON.stringify(`${m.toUpperCase()} ${path}`)}: {\n${lines.join("\n")}\n  };`);
    }
  }
  const E = opts.endpointsName ?? "Endpoints";
  out.push(`export interface ${E} {`, ...eps, "}", "");
  out.push(`/** Response body type of an endpoint: ResponseOf<"GET /products"> */`, `export type ResponseOf<K extends keyof ${E}> = ${E}[K]["response"];`, "");
  return out.join("\n");
}
