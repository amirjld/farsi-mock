// `farsi-mock frontend`: OpenAPI -> static mock module (spec + types + index), so the app never parses the spec at runtime.
import { compileOpenAPI, isOpenAPI, type CompileOptions } from "./compile.js";
import { openApiToTs } from "./typegen.js";
import type { MockSpec, Shape } from "./types.js";

export interface SnapshotOptions extends CompileOptions {
  /** "ts" (default): spec.ts, types.ts, index.ts. "js": spec.js, index.js (JSDoc types). "json": mock-spec.json only. */
  lang?: "ts" | "js" | "json";
  /** Seed and id written into index.ts. */
  seed?: number | string;
  id?: string;
  /** Where the frontend calls the API ("/api", "https://api.example.com/v1"); written into index.ts. */
  baseUrl?: string;
  /** Command shown in the generated headers. */
  command?: string;
  /** Import path of the runtime (default "farsi-mock/frontend/runtime"). */
  runtimeImport?: string;
}

const slug = (s: string) => s.toLowerCase().replace(/\(.*?\)/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "api";

/** Files to write, by file name. index.* is meant to be edited: only create it when missing. */
export function snapshotFiles(doc: unknown, opts: SnapshotOptions = {}): { files: Record<string, string>; spec: MockSpec; editable: string[] } {
  if (!isOpenAPI(doc)) throw new Error("farsi-mock: expected an OpenAPI 3.x or Swagger 2 document");
  const spec = compileOpenAPI(doc, opts);
  const lang = opts.lang ?? "ts";
  const cmd = opts.command ?? "npx farsi-mock frontend";
  const json = JSON.stringify(spec, null, 2);
  if (lang === "json") return { files: { "mock-spec.json": json + "\n" }, spec, editable: [] };
  const rt = opts.runtimeImport ?? "farsi-mock/frontend/runtime";
  const id = opts.id ?? slug(spec.title ?? "api");
  const seed = typeof opts.seed === "string" ? JSON.stringify(opts.seed) : String(opts.seed ?? 1);
  const head = `// Generated by farsi-mock from the API spec. Do not edit: re-run \`${cmd}\`.\n`;
  const optLines = [
    `  id: ${JSON.stringify(id)},`,
    `  seed: ${seed},`,
    ...(opts.baseUrl ? [`  baseUrl: ${JSON.stringify(opts.baseUrl)},`] : []),
    `  // delay: [150, 600],           // realistic latency`,
    `  // persist: true,               // keep created/edited records in localStorage`,
    `  // errors: { "GET /products": { status: 500, rate: 0.1 } },`,
    `  // handlers: { "GET /me": ({ f }) => ({ data: { fullName: f.person().fullName } }) },`,
  ];
  if (lang === "js") {
    return {
      spec, editable: ["index.js"],
      files: {
        "spec.js": `${head}/** @type {import("${rt}").MockSpec} */\nexport const spec = ${json};\n`,
        "index.js": `// Created by farsi-mock. Edit freely: \`${cmd}\` only rewrites spec.js.\nimport { createMockRuntime } from "${rt}";\nimport { spec } from "./spec.js";\n\nexport const api = createMockRuntime(spec, {\n${optLines.join("\n")}\n});\nexport default api;\n`,
      },
    };
  }
  return {
    spec, editable: ["index.ts"],
    files: {
      "spec.ts": `${head}import type { MockSpec } from "${rt}";\n\nexport const spec: MockSpec = ${json};\n`,
      "types.ts": openApiToTs(doc).replace(/^\/\/ Generated by farsi-mock[^\n]*\n/, head),
      "index.ts": `// Created by farsi-mock. Edit freely: \`${cmd}\` only rewrites spec.ts and types.ts.\nimport { createMockRuntime } from "${rt}";\nimport { spec } from "./spec";\nimport type { Endpoints } from "./types";\n\nexport * from "./types";\nexport const api = createMockRuntime<Endpoints>(spec, {\n${optLines.join("\n")}\n});\nexport default api;\n`,
    },
  };
}

const shapeSummary = (s: Shape | undefined, depth = 0): string => {
  if (!s) return "(empty)";
  switch (s.t) {
    case "object": return depth > 2 ? "{…}" : `{ ${Object.entries(s.props).map(([k, v]) => (v.t === "gen" || v.t === "const" || v.t === "now" ? k : `${k}: ${shapeSummary(v, depth + 1)}`)).join(", ")} }`;
    case "items": return `${s.resource}[]`;
    case "record": return s.resource;
    case "meta": return `$${s.role}`;
    case "array": return `${shapeSummary(s.of, depth + 1)}[]`;
    default: return s.t;
  }
};

/** One line per route: what the mock will do (for --explain). */
export function describeSpec(spec: MockSpec): string {
  const rows = spec.routes.map((r) => [`${r.method} ${spec.basePath}${r.path}`, r.kind + (r.resource ? ` ${r.resource}` : ""), String(r.status), shapeSummary(r.response)]);
  const w = [0, 1, 2].map((i) => Math.max(...rows.map((r) => r[i].length), 6));
  const res = Object.entries(spec.resources).map(([n, r]) => `  ${n}: ${Object.keys(r.fields).length} fields, id ${r.idField} (${r.idType}), ${r.count ?? 30} records`);
  return [...rows.map((r) => `${r[0].padEnd(w[0])}  ${r[1].padEnd(w[1])}  ${r[2].padEnd(3)}  ${r[3]}`), "", "resources:", ...res].join("\n");
}
