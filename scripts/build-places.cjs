// One-off: builds src/data/places.ts from a curated province/city list plus the
// national-ID prefix table published in @persian-tools/persian-tools (MIT).
// Usage: node scripts/build-places.cjs <cities.json> <nid.json>
const fs = require("fs");
const [citiesPath, nidPath] = process.argv.slice(2);
const provinces = JSON.parse(fs.readFileSync(citiesPath, "utf8"));
const nid = JSON.parse(fs.readFileSync(nidPath, "utf8"));
const norm = (s) => s.replace(/[\s\u200c()]/g, "").replace(/ي/g, "ی").replace(/ك/g, "ک");
// pre-2010 provinces in the source table: Alborz cities sit under Tehran; Zanjan city row is misfiled.
const srcProvince = { "البرز": ["تهران"], "زنجان": ["زنجان", "اصفهان"], "کهگیلویه و بویراحمد": ["کهکیلویه و بویراحمد"] };
const capitalAlias = { "تهران": "تهرانمرکزی", "یاسوج": "بویراحمدیاسوج", "دوگنبدان": "گچسارانداوگنبدان" };
let out = `// Generated by scripts/build-places.cjs. Do not edit by hand.\n// Provinces: ISO 3166-2:IR. Area codes: parsi-mcp. National-ID prefixes: @persian-tools/persian-tools (MIT), see DATA_SOURCES.md.\n\nexport interface City { fa: string; en: string; nidPrefixes: string[] }\nexport interface ProvinceData { iso: string; fa: string; en: string; areaCode: string; lat: number; lng: number; cities: City[] }\n\nexport const PROVINCES: ProvinceData[] = [\n`;
const missing = [];
for (const [iso, fa, en, area, lat, lng, cities] of provinces) {
  const srcs = srcProvince[fa] ?? [fa];
  const table = Object.assign({}, ...srcs.map((p) => nid[p] ?? {}));
  const cs = cities.map(([cfa, cen], i) => {
    const key = capitalAlias[cfa] ?? norm(cfa);
    let hit = Object.entries(table).find(([k]) => norm(k) === key) ?? Object.entries(table).find(([k]) => norm(k).startsWith(key));
    let prefixes = hit ? hit[1] : [];
    if (!prefixes.length) missing.push(cfa);
    return { fa: cfa, en: cen, nidPrefixes: prefixes };
  });
  // cities without a known prefix fall back to the capital's prefixes at runtime
  out += `  { iso: ${JSON.stringify(iso)}, fa: ${JSON.stringify(fa)}, en: ${JSON.stringify(en)}, areaCode: ${JSON.stringify(area)}, lat: ${lat}, lng: ${lng}, cities: [\n`;
  for (const c of cs) out += `    { fa: ${JSON.stringify(c.fa)}, en: ${JSON.stringify(c.en)}, nidPrefixes: ${JSON.stringify(c.nidPrefixes)} },\n`;
  out += `  ] },\n`;
}
out += `];\n`;
fs.writeFileSync("src/data/places.ts", out);
console.error("cities without prefix (fallback to capital):", missing.join(", "));
