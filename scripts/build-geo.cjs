// One-off: city-level coordinates from GeoNames (CC BY 4.0, https://www.geonames.org/).
// Usage: node scripts/build-geo.cjs IR.txt   (IR.txt from https://download.geonames.org/export/dump/IR.zip)
// Writes src/data/geo.ts with [lat, lng, radiusKm, population] per city. The radius is an
// approximation from population (GeoNames has points, not boundaries).
const fs = require("fs");
const src = fs.readFileSync("src/data/places.ts", "utf8");
const provinces = [...src.matchAll(/iso: "([^"]+)", fa: "([^"]+)", en: "([^"]+)".*?lat: ([\d.]+), lng: ([\d.]+), cities: \[([\s\S]*?)\n  \] \},/g)].map((m) => ({
  iso: m[1], lat: +m[4], lng: +m[5], cities: [...m[6].matchAll(/fa: "([^"]+)", en: "([^"]+)"/g)].map((c) => ({ fa: c[1], en: c[2] })),
}));
const rows = fs.readFileSync(process.argv[2], "utf8").split("\n").map((l) => l.split("\t")).filter((r) => r[6] === "P");
const norm = (s) => s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z]/g, "");
const normFa = (s) => s.replace(/[\s\u200c]/g, "").replace(/ي/g, "ی").replace(/ك/g, "ک");
const ALIAS = { Genaveh: "Bandar-e Genaveh", Talesh: "Hashtpar", Mahshahr: "Bandar-e Mahshahr" };
const km = (a, b, c, d) => { const R = 6371, t = Math.PI / 180; const x = (d - b) * t * Math.cos(((a + c) / 2) * t), y = (c - a) * t; return Math.sqrt(x * x + y * y) * R; };
let out = "// Generated by scripts/build-geo.cjs from GeoNames (CC BY 4.0). [lat, lng, radiusKm, population]\nexport const CITY_GEO: Record<string, [number, number, number, number]> = {\n";
const miss = [];
for (const p of provinces) for (const c of p.cities) {
  const en = norm(ALIAS[c.en] ?? c.en), fa = normFa(c.fa);
  const cand = rows.filter((r) => {
    const names = [r[1], r[2]].map(norm);
    const alts = (r[3] || "").split(",");
    return (names.includes(en) || alts.some((a) => normFa(a) === fa)) && km(p.lat, p.lng, +r[4], +r[5]) < 650;
  }).sort((a, b) => +b[14] - +a[14]);
  const r = cand[0];
  if (!r || +r[14] === 0) { miss.push(c.fa); continue; }
  const pop = +r[14];
  const radius = Math.max(2, Math.min(25, Math.round((Math.sqrt(pop) / 60) * 10) / 10));
  out += `  ${JSON.stringify(p.iso + "|" + c.fa)}: [${(+r[4]).toFixed(4)}, ${(+r[5]).toFixed(4)}, ${radius}, ${pop}],\n`;
}
out += "};\n";
fs.writeFileSync("src/data/geo.ts", out);
console.error("matched", (out.match(/\n  "/g) || []).length, "missing:", miss.join(", "));
